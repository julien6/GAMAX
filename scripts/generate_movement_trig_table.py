"""Generate mathematical lookup data at 80-bit significand precision.

Development-only mpmath dependency; emitted models need only Python/JAX.
The numeric scheme is documented in OpenJDK's x86 libm sin/cos stubs.
No OpenJDK source or lookup table is copied into the generated data.
"""
from pathlib import Path
import math,json
import mpmath as mp
mp.mp.dps=120

def extended(value):
    if not value:return mp.mpf(0)
    _,exponent=mp.frexp(value)
    return mp.ldexp(mp.nint(mp.ldexp(value,80-exponent)),exponent-80)

def table():
    rows=[]
    for index in range(64):
        angle=mp.pi*index/32
        s=extended(mp.sin(angle));c=extended(mp.cos(angle))
        if index%16==0:
            s=mp.mpf([0,1,0,-1][index//16]);c=mp.mpf([1,0,-1,0][index//16])
        if c:
            power=mp.power(2,mp.floor(mp.log(abs(c),2)))
            sigma=mp.sign(c)*(power if abs(c)-power<=2*power-abs(c) else 2*power)
        else:sigma=mp.mpf(0)
        high=float(s)
        rows.append([float(c-sigma),high,float(s-mp.mpf(high)),float(sigma)])
    return rows

if __name__=='__main__':
    destination=Path(__file__).resolve().parents[1]/'gamax/movement_trig_table.py'
    rows=table()
    destination.write_text('"""Mathematically generated by scripts/generate_movement_trig_table.py."""\nTABLE_HEX = '+repr([[v.hex() for v in row] for row in rows])+'\n')
